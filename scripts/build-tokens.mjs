// Builds Bookd design tokens (DTCG JSON in /tokens) into CSS custom properties
// and a typed JS map. Every output name is prefixed `bookd-` so nothing can
// collide with another design system loaded on the same page.
import StyleDictionary from 'style-dictionary';

const PREFIX = 'bookd';
const isSemantic = (token) => token.path[0] === 'semantic';

// Drop the leading `semantic` segment so names read --bookd-bg-white-0.
StyleDictionary.registerTransform({
  name: 'bookd/name/semantic-strip',
  type: 'name',
  transform: (token) =>
    [PREFIX, ...(isSemantic(token) ? token.path.slice(1) : token.path)].join('-'),
});

// Typed map of every token name -> its CSS var(), so components get
// autocomplete and a compile error on a typo'd token.
StyleDictionary.registerFormat({
  name: 'bookd/ts-vars',
  format: ({ dictionary }) => {
    const rows = dictionary.allTokens
      .map((t) => `  '${t.name}': 'var(--${t.name})',`)
      .join('\n');
    return `// Generated by scripts/build-tokens.mjs. Do not edit.\nexport const vars = {\n${rows}\n} as const;\n\nexport type BookdToken = keyof typeof vars;\n`;
  },
});

const transforms = [
  'attribute/cti',
  'bookd/name/semantic-strip',
  'color/css',
  'size/rem',
  'shadow/css/shorthand',
  'typography/css/shorthand',
  'fontFamily/css',
];

const base = new StyleDictionary({
  source: ['tokens/primitives/**/*.json'],
  log: { verbosity: 'silent' },
  platforms: {
    css: {
      transforms,
      buildPath: 'src/tokens/generated/',
      files: [{
        destination: 'primitives.css',
        format: 'css/variables',
        options: { selector: ':root', outputReferences: true },
      }],
    },
  },
});

// Semantic names are identical across themes, so the light set defines the TS map.
const tsMap = new StyleDictionary({
  source: ['tokens/primitives/**/*.json', 'tokens/themes/light.json'],
  log: { verbosity: 'silent' },
  platforms: {
    ts: {
      transforms,
      buildPath: 'src/tokens/generated/',
      files: [{ destination: 'vars.ts', format: 'bookd/ts-vars' }],
    },
  },
});

const theme = (name, selector) =>
  new StyleDictionary({
    include: ['tokens/primitives/**/*.json'],
    source: [`tokens/themes/${name}.json`],
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transforms,
        buildPath: 'src/tokens/generated/',
        files: [{
          destination: `theme-${name}.css`,
          format: 'css/variables',
          filter: isSemantic,
          options: { selector, outputReferences: true },
        }],
      },
    },
  });

await base.buildAllPlatforms();
await tsMap.buildAllPlatforms();
// Gradient Ticket is dark-first: dark is the default on :root, light is opt-in.
await theme('dark', ':root, [data-bookd-theme="dark"]').buildAllPlatforms();
await theme('light', '[data-bookd-theme="light"]').buildAllPlatforms();
console.log('✓ Bookd tokens built to src/tokens/generated/');
